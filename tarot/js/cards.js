for (const [suit, data] of Object.entries(MINOR_DATA)) {
  for (const [n, label, up, rev] of data.cards) {
    const numRoman = n <= 10 ? n : { 11: "Page", 12: "Knight", 13: "Queen", 14: "King" }[n];
    const courtCN = { Page: "侍从", Knight: "骑士", Queen: "王后", King: "国王" };
    const cn = n <= 10
      ? `${data.suit_cn}${["", "首牌", "二", "三", "四", "五", "六", "七", "八", "九", "十"][n]}`
      : `${data.suit_cn}${courtCN[label]}`;
    MINOR.push({
      id: `${suit}-${String(n).padStart(2, "0")}`,
      num: typeof numRoman === "number" ? String(numRoman) : numRoman,
      name: `${label} of ${suit[0].toUpperCase() + suit.slice(1)}`,
      cn,
      glyph: SUIT_GLYPH[suit],
      suit,
      up, rev,
    });
  }
}

